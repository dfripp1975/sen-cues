#!/usr/bin/env node
// Validates the authored seed content against the World English Bible text and
// generates supabase/migrations/20261014000002_seed_content.sql.
//
//  - every reference must parse and exist in the WEB data;
//  - every quotation in "double quotes" inside a devotional reflection, journey
//    explanation or quiz explanation must appear verbatim somewhere in the WEB,
//    so the app never puts invented words into Scripture's mouth;
//  - devotional reflections must be 300–500 words.
//
// Usage: node scripts/build-seed.mjs          (validate + write migration)
//        node scripts/build-seed.mjs --check  (validate only; exits 1 on problems)

import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { parseReference } from '../supabase/functions/_shared/bibleRef.ts';
import dailyVerses from './content/daily-verses.mjs';
import devotionals from './content/devotionals.mjs';
import journeys from './content/journeys.mjs';
import quiz from './content/quiz.mjs';
import { MOODS } from '../src/content/options.ts';
import { SCRIPTURE_AUDIO, MEDITATIONS } from '../src/content/audio.ts';

const here = dirname(fileURLToPath(import.meta.url));
const bible = JSON.parse(gunzipSync(readFileSync(join(here, '../supabase/seed/web-bible.json.gz'))).toString('utf8'));
const problems = [];

const simplify = (s) =>
  s.toLowerCase().replace(/[‘’`]/g, "'").replace(/[“”]/g, '"').replace(/[—–-]/g, ' ').replace(/[^a-z0-9' ]/g, ' ').replace(/\s+/g, ' ').trim();
const corpus = simplify(bible.books.flatMap((b) => b.chapters.flat()).join(' '));

function resolve(refStr, where) {
  const r = parseReference(refStr);
  if (!r) {
    problems.push(`${where}: cannot parse reference "${refStr}"`);
    return null;
  }
  const chapter = bible.books[r.bookId - 1].chapters[r.chapter - 1];
  const vs = r.verseStart ?? 1;
  const ve = r.verseEnd ?? chapter.length;
  if (ve > chapter.length) {
    problems.push(`${where}: "${refStr}" — chapter has only ${chapter.length} verses`);
    return null;
  }
  return { ...r, verseStart: vs, verseEnd: ve };
}

function checkQuotes(text, where) {
  // Only straight double quotes are treated as Scripture quotations.
  for (const m of text.matchAll(/"([^"\n]{6,})"/g)) {
    const q = simplify(m[1]);
    if (!corpus.includes(q)) problems.push(`${where}: quotation not found in WEB text: "${m[1]}"`);
  }
}

const sq = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(sq).join(',')}]::text[]`;
const out = ['-- Generated by scripts/build-seed.mjs — edit scripts/content/* and re-run instead of editing by hand.', 'begin;'];

// Translation + book metadata (verse text itself is loaded by scripts/import-bible.mjs).
const t = bible.translation;
out.push(`insert into public.bible_translations (code, name, language, license, copyright_notice) values (${sq(t.code)}, ${sq(t.name)}, ${sq(t.language)}, ${sq(t.license)}, ${sq(t.notice)}) on conflict (code) do nothing;`);
out.push('insert into public.bible_books (id, code, name, testament, chapter_count) values');
out.push(bible.books.map((b) => `(${b.order}, ${sq(b.code)}, ${sq(b.name)}, ${sq(b.testament)}, ${b.chapters.length})`).join(',\n') + '\non conflict (id) do nothing;');

// Daily verses
const dvRows = dailyVerses.map((d, i) => {
  const r = resolve(d.ref, `daily verse #${i}`);
  checkQuotes(d.explanation, `daily verse ${d.ref}`);
  return r && `(${i}, ${r.bookId}, ${r.chapter}, ${r.verseStart}, ${r.verseEnd}, ${sq(d.explanation)}, ${sq(d.theme)})`;
});
out.push('insert into public.daily_verses (id, book_id, chapter, verse_start, verse_end, explanation, theme) values');
out.push(dvRows.join(',\n') + '\non conflict (id) do update set book_id = excluded.book_id, chapter = excluded.chapter, verse_start = excluded.verse_start, verse_end = excluded.verse_end, explanation = excluded.explanation, theme = excluded.theme;');

// Devotionals
devotionals.forEach((d, i) => {
  const r = resolve(d.ref, `devotional ${d.slug}`);
  const words = d.reflection.split(/\s+/).filter(Boolean).length;
  if (words < 300 || words > 500) problems.push(`devotional ${d.slug}: reflection is ${words} words (needs 300–500)`);
  checkQuotes(d.reflection, `devotional ${d.slug}`);
  if (!r) return;
  out.push(
    `insert into public.devotional_content (slug, title, book_id, chapter, verse_start, verse_end, reflection, takeaway, reflection_question, prayer, focus_tags, is_premium, sort_order) values (${sq(d.slug)}, ${sq(d.title)}, ${r.bookId}, ${r.chapter}, ${r.verseStart}, ${r.verseEnd}, ${sq(d.reflection)}, ${sq(d.takeaway)}, ${sq(d.question)}, ${sq(d.prayer)}, ${arr(d.focus)}, ${d.premium ? 'true' : 'false'}, ${i}) on conflict (slug) do update set title = excluded.title, book_id = excluded.book_id, chapter = excluded.chapter, verse_start = excluded.verse_start, verse_end = excluded.verse_end, reflection = excluded.reflection, takeaway = excluded.takeaway, reflection_question = excluded.reflection_question, prayer = excluded.prayer, focus_tags = excluded.focus_tags, is_premium = excluded.is_premium, sort_order = excluded.sort_order;`,
  );
});

// Journeys
journeys.forEach((j, i) => {
  if (j.days.length === 0) problems.push(`journey ${j.slug}: has no days`);
  out.push(
    `insert into public.faith_journeys (slug, title, subtitle, description, day_count, focus_tags, is_premium, sort_order) values (${sq(j.slug)}, ${sq(j.title)}, ${sq(j.subtitle)}, ${sq(j.description)}, ${j.days.length}, ${arr(j.focus)}, ${j.premium ? 'true' : 'false'}, ${i}) on conflict (slug) do update set title = excluded.title, subtitle = excluded.subtitle, description = excluded.description, day_count = excluded.day_count, focus_tags = excluded.focus_tags, is_premium = excluded.is_premium, sort_order = excluded.sort_order;`,
  );
  j.days.forEach((d, n) => {
    const where = `journey ${j.slug} day ${n + 1}`;
    const r = resolve(d.ref, where);
    for (const k of ['explanation', 'question', 'activity', 'prayer', 'journal']) {
      if (!d[k]) problems.push(`${where}: missing ${k}`);
    }
    checkQuotes(d.explanation, where);
    checkQuotes(d.activity, where);
    if (!r) return;
    out.push(
      `insert into public.journey_days (journey_id, day_number, theme, book_id, chapter, verse_start, verse_end, explanation, reflection_question, activity, prayer, journal_prompt) select id, ${n + 1}, ${sq(d.theme)}, ${r.bookId}, ${r.chapter}, ${r.verseStart}, ${r.verseEnd}, ${sq(d.explanation)}, ${sq(d.question)}, ${sq(d.activity)}, ${sq(d.prayer)}, ${sq(d.journal)} from public.faith_journeys where slug = ${sq(j.slug)} on conflict (journey_id, day_number) do update set theme = excluded.theme, book_id = excluded.book_id, chapter = excluded.chapter, verse_start = excluded.verse_start, verse_end = excluded.verse_end, explanation = excluded.explanation, reflection_question = excluded.reflection_question, activity = excluded.activity, prayer = excluded.prayer, journal_prompt = excluded.journal_prompt;`,
    );
  });
});

// Quiz — wiped and reinserted (no stable key); quiz_results do not reference questions.
// Re-running replaces the seeded questions only; questions added by admins are untouched.
out.push(`delete from public.quiz_questions where question in (${quiz.map((q) => sq(q.q)).join(', ')});`);
const qRows = quiz.map((q, i) => {
  if (q.answer < 0 || q.answer >= q.options.length) problems.push(`quiz #${i}: answer index out of range`);
  checkQuotes(q.explanation, `quiz #${i} (${q.q.slice(0, 40)}…)`);
  checkQuotes(q.q, `quiz #${i} question`);
  return resolve(q.ref, `quiz #${i}`) && `(${sq(q.category)}, ${sq(q.difficulty)}, ${sq(q.q)}, ${arr(q.options)}, ${q.answer}, ${sq(q.explanation)}, ${sq(q.ref)})`;
});
out.push('insert into public.quiz_questions (category, difficulty, question, options, correct_index, explanation, reference) values');
out.push(qRows.join(',\n') + ';');
out.push('commit;');

// References used by the app's built-in mood check-in and audio library.
for (const m of MOODS) m.refs.forEach((r) => resolve(r, `mood ${m.id}`));
for (const a of SCRIPTURE_AUDIO) a.refs.forEach((r) => resolve(r, `audio ${a.id}`));
for (const m of MEDITATIONS) resolve(m.ref, `meditation ${m.id}`);

if (problems.length) {
  console.error(`Seed content problems (${problems.length}):\n- ` + problems.join('\n- '));
  process.exit(1);
}
const days = journeys.reduce((n, j) => n + j.days.length, 0);
console.log(`OK: ${dailyVerses.length} daily verses, ${devotionals.length} devotionals, ${journeys.length} journeys (${days} days), ${quiz.length} quiz questions.`);
if (!process.argv.includes('--check')) {
  const target = join(here, '../supabase/migrations/20261014000002_seed_content.sql');
  writeFileSync(target, out.join('\n') + '\n');
  console.log(`Wrote ${target}`);
}
